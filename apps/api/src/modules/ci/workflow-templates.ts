import { AppError } from "../../common/errors/app-error.js";

import type { DetectedStack } from "./stack-detector.js";

/**
 * Deterministic, versioned GitHub Actions workflow generation. NO AI-generated
 * YAML — a reviewed template is rendered from the detected stack, emitting steps
 * only for scripts that exist. The version marker at the top lets DevInside
 * recognize its own workflow and, later, update it (e.g. to add SonarQube) via a
 * fresh pull request without clobbering hand edits. Unsupported stacks throw
 * rather than producing a fake workflow.
 *
 * v3 adds secure, coverage-aware SonarQube scanning and optional Prisma
 * preparation. The self-contained **code_quality** job
 * is emitted only when a `sonarProjectKey` is passed (i.e. the repo has been
 * provisioned for automated code quality — project created + analysis token
 * injected as a repo secret). Because SonarQube Community Edition analyzes the
 * main branch only, the scan runs on **push to the default branch** (post-merge),
 * never on pull requests, so feature-branch noise can't pollute the main view.
 */

export const MANAGED_WORKFLOW_PATH = ".github/workflows/devinside-ci.yml";
export const MANAGED_MARKER_PREFIX = "# devinside-managed:";

const TEMPLATE_ID = "node";
const TEMPLATE_VERSION = "3";

// Immutable v8.1.0 commit. v4 is affected by CVE-2025-58178; pinning the exact
// patched commit also prevents a mutable tag from changing the executed action.
const SONAR_SCAN_ACTION =
  "SonarSource/sonarqube-scan-action@7006c4492b2e0ee0f816d36501671557c97f5995";

export type GenerateWorkflowOptions = {
  /**
   * When set, the workflow includes a SonarQube scan job for this project key.
   * The analysis token + host URL are supplied at runtime via repo secrets
   * (SONAR_TOKEN / SONAR_HOST_URL) injected during provisioning — never baked in.
   */
  sonarProjectKey?: string | null;
};

export type GeneratedWorkflow = {
  templateId: string;
  templateVersion: string;
  path: string;
  content: string;
};

function packageCommands(stack: DetectedStack): { runCmd: string; installCmd: string } {
  const pm = stack.packageManager;
  return {
    runCmd: pm === "pnpm" ? "pnpm run" : pm === "yarn" ? "yarn run" : "npm run",
    installCmd:
      pm === "pnpm"
        ? "pnpm install --frozen-lockfile"
        : pm === "yarn"
          ? "yarn install --frozen-lockfile"
          : "npm ci"
  };
}

/** Shared deterministic checkout/runtime/install preparation for each job. */
function preparationSteps(stack: DetectedStack, fullHistory: boolean): string[] {
  const { runCmd, installCmd } = packageCommands(stack);
  const steps: string[] = ["      - name: Checkout", "        uses: actions/checkout@v4"];
  if (fullHistory) {
    steps.push(
      "        with:",
      "          # Full history so SonarQube can attribute issues by SCM blame.",
      "          fetch-depth: 0"
    );
  }
  if (stack.packageManager === "pnpm") {
    steps.push("      - name: Set up pnpm", "        uses: pnpm/action-setup@v4");
  }
  steps.push(
    "      - name: Set up Node.js",
    "        uses: actions/setup-node@v4",
    "        with:",
    `          node-version: "${stack.nodeVersion}"`,
    `          cache: "${stack.packageManager}"`,
    "      - name: Install dependencies",
    `        run: ${installCmd}`
  );
  if (stack.scripts.prismaGenerate) {
    steps.push("      - name: Generate Prisma client", `        run: ${runCmd} prisma:generate`);
  }
  return steps;
}

/** Parses the `# devinside-managed: <id>@v<version>` marker; null if absent. */
export function parseManagedMarker(
  content: string
): { templateId: string; templateVersion: string } | null {
  const match = content.match(/^#\s*devinside-managed:\s*([a-z0-9-]+)@v(\d+)/im);
  return match ? { templateId: match[1]!, templateVersion: match[2]! } : null;
}

export function generateWorkflow(
  stack: DetectedStack,
  options: GenerateWorkflowOptions = {}
): GeneratedWorkflow {
  if (!stack.supported) {
    throw new AppError(
      400,
      stack.reason ?? "This repository's stack is not supported yet.",
      "STACK_UNSUPPORTED"
    );
  }

  const { runCmd } = packageCommands(stack);
  const steps = preparationSteps(stack, false);
  if (stack.scripts.lint) {
    steps.push("      - name: Lint", `        run: ${runCmd} lint`);
  }
  if (stack.scripts.typecheck) {
    steps.push("      - name: Typecheck", `        run: ${runCmd} typecheck`);
  }
  if (stack.scripts.test) {
    steps.push("      - name: Test", `        run: ${runCmd} test`);
  }
  if (stack.scripts.build) {
    steps.push("      - name: Build", `        run: ${runCmd} build`);
  }

  const sonarProjectKey = options.sonarProjectKey?.trim() || null;

  const lines: string[] = [
    `${MANAGED_MARKER_PREFIX} ${TEMPLATE_ID}@v${TEMPLATE_VERSION}`,
    "# Generated by DevInside. Manage this workflow from the DevInside dashboard;",
    "# DevInside may update it (e.g. add code-quality or security scanning) via a",
    "# pull request. Editing it by hand can cause update conflicts.",
    "name: CI",
    "",
    "on:",
    "  push:",
    `    branches: ["${stack.defaultBranch}"]`,
    "  pull_request:",
    "  workflow_dispatch:",
    "",
    "permissions:",
    "  contents: read",
    "",
    "jobs:",
    "  verify:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    ...steps
  ];

  if (sonarProjectKey) {
    const sonarSteps = preparationSteps(stack, true);
    if (stack.scripts.testCoverage) {
      sonarSteps.push(
        "      - name: Generate test coverage",
        `        run: ${runCmd} test:coverage`
      );
    }
    lines.push(
      "",
      "  code_quality:",
      "    # SonarQube Community Edition analyzes the main branch only, so scan on",
      "    # push (post-merge) — never on pull requests.",
      "    if: github.event_name == 'push'",
      "    runs-on: ubuntu-latest",
      "    steps:",
      ...sonarSteps,
      "      - name: SonarQube Scan",
      `        uses: ${SONAR_SCAN_ACTION}`,
      "        env:",
      "          SONAR_TOKEN: ${{ secrets.SONAR_TOKEN }}",
      "          SONAR_HOST_URL: ${{ secrets.SONAR_HOST_URL }}",
      "        with:",
      "          args: >",
      `            -Dsonar.projectKey=${sonarProjectKey}`,
      "            -Dsonar.qualitygate.wait=true",
      "            -Dsonar.qualitygate.timeout=300"
    );
  }

  lines.push("");
  const content = lines.join("\n");

  return {
    templateId: TEMPLATE_ID,
    templateVersion: TEMPLATE_VERSION,
    path: MANAGED_WORKFLOW_PATH,
    content
  };
}
